import { expect,test } from "@playwright/test";
import { createIsolatedBalanceFixture,loginIsolatedBalanceUser } from "./isolated-balance-fixture";

test("취향 진열장: 기본형·겹침·장식·수량·저장 실패·방문·모바일",async({page,browser},info)=>{
  test.setTimeout(180_000);
  const f=await createIsolatedBalanceFixture(2);
  const owner=await f.memberClient(0);
  const visitor=await browser.newContext();
  try{
    for(const catalogId of ["wood-label","trailing-ivy","potted-plant","pastel-books","star-mug"]){const {error}=await owner.rpc("claim_showcase_product",{p_catalog_id:catalogId});expect(error).toBeNull();}
    await loginIsolatedBalanceUser(page,f.users[0]);
    await page.goto("/store");
    await page.getByRole("button",{name:"황동 조명 1개 받기",exact:true}).click();
    await expect(page.getByRole("article",{name:"황동 조명",exact:true})).toContainText("보유 1개");
    await page.goto("/profile");
    const showcase=page.getByRole("region",{name:"취향 진열장",exact:true});
    await expect(showcase.getByTestId("showcase-scene")).toBeVisible();
    await expect(showcase.locator("canvas")).toHaveCount(0);
    await expect(showcase.getByTestId("showcase-light-beam")).toHaveCount(0);
    const keyboard=showcase.getByRole("img",{name:"세이지 키보드",exact:true});
    const keyboardBounds=await keyboard.boundingBox();
    expect(keyboardBounds!.width/keyboardBounds!.height).toBeGreaterThan(4);
    // Wait for both CSS backgrounds and SVG image assets before visual evidence.
    await page.evaluate(async()=>{
      const scene=document.querySelector('[data-testid="showcase-scene"]')!;
      const urls=new Set<string>();
      scene.querySelectorAll("*").forEach(element=>{
        if(element.tagName==="image") urls.add(element.getAttribute("href")!);
        const match=getComputedStyle(element).backgroundImage.match(/url\(["']?([^"')]+)["']?\)/);
        if(match) urls.add(match[1]);
      });
      await Promise.all([...urls].map(async src=>{const image=new Image();image.src=src;await image.decode();}));
    });
    await page.screenshot({path:info.outputPath("showcase-focus.png"),fullPage:true});
    await showcase.getByRole("button",{name:"꾸미기",exact:true}).click();
    await showcase.getByRole("button",{name:"황동 조명 꺼내기",exact:true}).click();
    const lamp=showcase.getByRole("button",{name:"황동 조명 선택",exact:true});
    const beams=showcase.getByTestId("showcase-light-beam");
    await expect(beams).toHaveCount(1);
    await expect(showcase.getByRole("button",{name:"황동 조명 꺼내기",exact:true})).toBeDisabled();
    await showcase.getByLabel("조명 설치 위치",{exact:true}).selectOption("0");
    const upperLamp=await lamp.boundingBox();
    await showcase.getByLabel("조명 설치 위치",{exact:true}).selectOption("1");
    expect((await lamp.boundingBox())!.y).toBeGreaterThan(upperLamp!.y+50);
    const oldBeam=await beams.boundingBox();
    await showcase.getByLabel("굿즈 좌우 위치",{exact:true}).fill("15");
    expect((await beams.boundingBox())!.x).toBeLessThan(oldBeam!.x);
    await showcase.getByTestId("showcase-scene").scrollIntoViewIfNeeded();
    const lampBox=(await lamp.boundingBox())!;
    const sceneBox=(await showcase.getByTestId("showcase-scene").boundingBox())!;
    await page.mouse.move(lampBox.x+lampBox.width/2,lampBox.y+lampBox.height/2);
    await page.mouse.down();
    await page.mouse.move(sceneBox.x+sceneBox.width*.5,sceneBox.y+sceneBox.height*.76,{steps:8});
    await page.mouse.up();
    await expect(showcase.getByLabel("조명 설치 위치",{exact:true})).toHaveValue("2");
    await showcase.getByLabel("조명 설치 위치",{exact:true}).selectOption("0");
    await showcase.getByLabel("굿즈 좌우 위치",{exact:true}).fill("50");
    await showcase.getByRole("button",{name:"저장하고 닫기",exact:true}).first().click();
    await page.reload();
    await expect(beams).toHaveCount(1);
    await page.screenshot({path:info.outputPath("showcase-light-focus.png"),fullPage:true});
    await showcase.getByRole("button",{name:"꾸미기",exact:true}).click();
    await lamp.click();
    await showcase.getByRole("button",{name:"보관함에 넣기",exact:true}).click();
    await expect(beams).toHaveCount(0);
    await expect(showcase.getByRole("button",{name:"황동 조명 꺼내기",exact:true})).toBeEnabled();
    await showcase.getByLabel("진열장 이름",{exact:true}).fill("나의 초록 취향");
    await showcase.getByLabel("선반 모양",{exact:true}).selectOption("classic");
    await page.getByRole("dialog").getByRole("button",{name:"이 모양 적용"}).click();
    await page.screenshot({path:info.outputPath("showcase-classic-three.png"),fullPage:true});
    for(const [name,x] of [["초록 화분","10"],["취향의 책","50"],["별빛 머그","90"]]){
      await showcase.getByRole("button",{name:`${name} 꺼내기`,exact:true}).click();
      await showcase.getByLabel("굿즈 선반",{exact:true}).selectOption("2");
      await showcase.getByLabel("굿즈 좌우 위치",{exact:true}).fill(x);
    }
    await showcase.getByRole("button",{name:"작은 여우 선택",exact:true}).click();
    await showcase.getByLabel("굿즈 선반",{exact:true}).selectOption("0");
    await showcase.getByLabel("굿즈 겹침 순서",{exact:true}).selectOption("8");
    await showcase.getByLabel("굿즈 좌우 위치",{exact:true}).fill("50");
    await showcase.getByRole("button",{name:"나무 주제 명패 꺼내기",exact:true}).click();
    await showcase.getByLabel("명패 문구",{exact:true}).fill("나의 작은 숲");
    await showcase.getByLabel("굿즈 좌우 위치",{exact:true}).fill("10");
    await showcase.getByRole("button",{name:"늘어진 이파리 꺼내기",exact:true}).click();
    await showcase.getByLabel("굿즈 좌우 위치",{exact:true}).fill("95");
    await showcase.getByRole("button",{name:"황동 조명 꺼내기",exact:true}).click();
    await showcase.getByLabel("굿즈 좌우 위치",{exact:true}).fill("85");
    await showcase.getByRole("button",{name:"새 진열장",exact:true}).click();
    await showcase.getByLabel("진열장 이름",{exact:true}).fill("두 번째 취향");
    await expect(showcase.getByRole("button",{name:"작은 여우 꺼내기",exact:true})).toBeDisabled();
    await expect(showcase.getByRole("button",{name:"황동 조명 꺼내기",exact:true})).toBeDisabled();
    await showcase.getByRole("button",{name:"대표로 설정",exact:true}).click();
    let fail=true;
    await page.route("**/profile",async route=>{if(fail&&route.request().method()==="POST"){fail=false;return route.abort("failed");}return route.continue();});
    await showcase.getByRole("button",{name:"저장하고 닫기",exact:true}).first().click();
    await expect(showcase.getByRole("alert")).toContainText("저장하지 못했습니다");
    await expect(showcase.getByLabel("진열장 이름",{exact:true})).toHaveValue("두 번째 취향");
    await showcase.getByRole("button",{name:"다시 저장",exact:true}).click();
    await expect(showcase.getByRole("button",{name:"꾸미기",exact:true})).toBeVisible();
    await page.unroute("**/profile");await page.reload();
    await expect(showcase.getByRole("heading",{name:"두 번째 취향"})).toBeVisible();
    await showcase.getByLabel("진열장 선택",{exact:true}).selectOption({label:"나의 초록 취향"});
    await expect(showcase.getByRole("img",{name:"나무 주제 명패 · 나의 작은 숲"})).toBeVisible();
    await page.screenshot({path:info.outputPath("showcase-desktop.png"),fullPage:true});
    for(const width of [802,390,320]){await page.setViewportSize({width,height:950});await expect(showcase).toBeVisible();expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);}
    await page.screenshot({path:info.outputPath("showcase-mobile.png"),fullPage:true});
    const visiting=await visitor.newPage();await loginIsolatedBalanceUser(visiting,f.users[1]);await visiting.goto(`/profile/${f.users[0].id}`);
    await expect(visiting.getByRole("heading",{name:"두 번째 취향"})).toBeVisible();
    await expect(visiting.getByRole("button",{name:"꾸미기",exact:true})).toHaveCount(0);
    await page.goto("/store");await page.getByRole("button",{name:"작은 여우 1개 받기",exact:true}).click();
    await expect(page.getByRole("article",{name:"작은 여우",exact:true})).toContainText("보유 2개");
    await page.goto("/profile");await showcase.getByRole("button",{name:"꾸미기",exact:true}).click();
    await showcase.getByRole("button",{name:"작은 여우 꺼내기",exact:true}).click();
    await showcase.getByRole("button",{name:"저장하고 닫기",exact:true}).first().click();
    await expect(showcase.getByRole("button",{name:"꾸미기",exact:true})).toBeVisible();
    await showcase.getByRole("button",{name:"꾸미기",exact:true}).click();
    await showcase.getByRole("button",{name:"구성 복사",exact:true}).click();
    await expect(showcase.getByRole("button",{name:"작은 여우 꺼내기",exact:true})).toBeDisabled();
    await expect(showcase.getByTestId("showcase-scene")).toContainText("좋아하는 것부터 하나씩.");
    await showcase.getByRole("button",{name:"진열장 삭제",exact:true}).click();
    await page.getByRole("dialog").getByRole("button",{name:"삭제",exact:true}).click();
    await showcase.getByRole("button",{name:"저장하고 닫기",exact:true}).first().click();
    await expect(showcase.getByRole("button",{name:"꾸미기",exact:true})).toBeVisible();
    const latest=await f.service.from("user_showcase_libraries").select("revision,document").eq("user_id",f.users[0].id).single();
    expect(latest.error).toBeNull();
    await showcase.getByRole("button",{name:"꾸미기",exact:true}).click();
    await showcase.getByLabel("진열장 이름",{exact:true}).fill("저장 충돌 초안");
    expect((await f.service.from("user_showcase_libraries").update({revision:latest.data!.revision+1,document:latest.data!.document}).eq("user_id",f.users[0].id)).error).toBeNull();
    await showcase.getByRole("button",{name:"저장하고 닫기",exact:true}).first().click();
    await expect(showcase.getByRole("alert")).toContainText("다른 화면에서 변경되었습니다");
    await expect(showcase.getByLabel("진열장 이름",{exact:true})).toHaveValue("저장 충돌 초안");
    await showcase.getByRole("button",{name:"최신 내용 불러오기",exact:true}).click();
    await page.getByRole("dialog").getByRole("button",{name:"최신 내용 불러오기",exact:true}).click();
    await expect(showcase.getByRole("button",{name:"꾸미기",exact:true})).toBeVisible();
    await showcase.getByRole("button",{name:"꾸미기",exact:true}).click();
    await showcase.getByLabel("진열장 이름",{exact:true}).fill("계정 변경 초안");
    await page.context().clearCookies();await page.context().addCookies(await visitor.cookies());
    await showcase.getByRole("button",{name:"저장하고 닫기",exact:true}).first().click();
    await expect(showcase.getByRole("alert")).toContainText("계정이 변경되었습니다");
  }finally{await visitor.close();await owner.auth.signOut();await f.cleanup();}
});
