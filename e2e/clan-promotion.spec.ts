    await expect.poll(async()=>{
      const result=await f.service.from("clans").select("tier_range").eq("id",createdId!).single();
      expect(result.error).toBeNull(); return result.data?.tier_range;
    }).toEqual(["ascendant","immortal","radiant"]);
