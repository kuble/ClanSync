import {expect,test} from '@playwright/test';
import {createIsolatedBalanceFixture,loginIsolatedBalanceUser} from './isolated-balance-fixture';
test.use({actionTimeout:20_000});
async function ok<T>(query:PromiseLike<{data:T;error:unknown}>){const {data,error}=await query;expect(error,JSON.stringify(error)).toBeNull();return data as NonNullable<T>;}
test('클랜원 선생님 등록·지정 신청·담당 상태·참여자 댓글 알림과 신청 중단',async({page})=>{
  test.setTimeout(240_000);
  const f=await createIsolatedBalanceFixture(3),base=f.path.replace(/\/balance$/,''),coach=f.users[2],student=f.users[1],peer=f.users[0];
  try{
    await loginIsolatedBalanceUser(page,coach);await page.goto(base+'/board/feedback');
    await page.getByRole('button',{name:'코칭 선생님 등록',exact:true}).click();
    const dialog=page.getByRole('dialog');
    await dialog.getByLabel('코칭 분야·역할·영웅',{exact:true}).fill('지원 · 아나 · 위치 선정');
    await dialog.getByLabel('선생님 소개',{exact:true}).fill('리플레이를 같이 보며 다음 한타를 준비해요.');
    await dialog.getByRole('button',{name:'프로필 저장',exact:true}).click();
    await expect(page.getByRole('button',{name:'내 코칭 프로필',exact:true})).toBeVisible();
    await page.context().clearCookies();await loginIsolatedBalanceUser(page,student);await page.goto(base+'/board/feedback');
    await page.getByRole('button',{name:coach.nickname+' 선생님께 신청',exact:true}).click();
    await expect(dialog.getByLabel('코칭 선생님',{exact:true})).toHaveValue(coach.id);
    await dialog.getByLabel('제목',{exact:true}).fill('첫 한타 위치를 봐 주세요');
    await dialog.getByLabel('역할·영웅',{exact:true}).fill('지원 · 아나');
    await dialog.getByLabel('리플레이 코드',{exact:true}).fill('ABC123');
    await dialog.getByLabel('궁금한 점',{exact:true}).fill('첫 한타에서 어떤 엄폐물을 써야 할까요?');
    await dialog.getByRole('button',{name:'저장',exact:true}).click();
    await expect(page).toHaveURL(/\/board\/feedback\/[0-9a-f-]{36}$/,{timeout:20000});
    const postId=page.url().split('/').at(-1)!;
    await expect(page.getByRole('region',{name:'코칭 신청 정보',exact:true}).getByText(coach.nickname,{exact:true})).toBeVisible();
    const notify=await ok(f.service.from('notifications').select('recipient_user_id').eq('kind','coaching_requested').eq('source_id',postId));
    expect(notify.map(r=>r.recipient_user_id)).toEqual([coach.id]);
    await page.context().clearCookies();await loginIsolatedBalanceUser(page,coach);await page.goto(base+'/board/feedback');
    await page.getByRole('button',{name:/^알림/}).click();
    await page.getByRole('button',{name:/새 코칭 신청 · 첫 한타 위치를 봐 주세요/}).click();
    await expect(page).toHaveURL(new RegExp(postId+'$'));
    await expect(page.getByRole('button',{name:'편집',exact:true})).toHaveCount(0);
    await page.getByLabel('신청 상태',{exact:true}).selectOption('answering');
    await expect.poll(async()=>(await ok(f.service.from('clan_board_posts').select('status').eq('id',postId).single())).status).toBe('answering');
    await page.getByLabel('댓글 내용',{exact:true}).fill('왼쪽 기둥 뒤로 이동해 보세요.');
    await page.getByRole('button',{name:'댓글 등록',exact:true}).click();
    await expect(page.getByRole('listitem').filter({hasText:'왼쪽 기둥 뒤로 이동해 보세요.'})).toBeVisible();
    await page.context().clearCookies();await loginIsolatedBalanceUser(page,peer);await page.goto(base+'/board/feedback/'+postId);
    await page.getByLabel('댓글 내용',{exact:true}).fill('저도 같은 장면이 궁금해요.');
    await page.getByRole('button',{name:'댓글 등록',exact:true}).click();
    await expect(page.getByRole('listitem').filter({hasText:'저도 같은 장면이 궁금해요.'})).toBeVisible();
    await page.context().clearCookies();await loginIsolatedBalanceUser(page,student);await page.goto(base+'/board/feedback');
    await page.getByRole('button',{name:/^알림/}).click();
    await page.getByRole('button',{name:/코칭 댓글 · 첫 한타 위치를 봐 주세요/}).first().click();
    await expect(page).toHaveURL(new RegExp(postId+'#comments$'));
    await page.getByLabel('댓글 내용',{exact:true}).fill('다음 경기에서 적용해 볼게요.');
    await page.getByRole('button',{name:'댓글 등록',exact:true}).click();
    await expect(page.getByRole('listitem').filter({hasText:'다음 경기에서 적용해 볼게요.'})).toBeVisible();
    const reply=await ok(f.service.from('clan_board_comments').select('id').eq('post_id',postId).eq('content','다음 경기에서 적용해 볼게요.').single());
    const participants=await ok(f.service.from('notifications').select('recipient_user_id').eq('source_id',reply.id));
    expect(new Set(participants.map(p=>p.recipient_user_id))).toEqual(new Set([peer.id,coach.id]));
    await page.context().clearCookies();await loginIsolatedBalanceUser(page,coach);await page.goto(base+'/board/feedback');
    await page.getByRole('button',{name:'내 코칭 프로필',exact:true}).click();
    await dialog.getByLabel('피드백 신청 받기',{exact:true}).uncheck();
    await dialog.getByRole('button',{name:'프로필 저장',exact:true}).click();
    await expect(page.getByText('신청 잠시 중단',{exact:true})).toBeVisible();
    await page.setViewportSize({width:390,height:844});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await page.context().clearCookies();await loginIsolatedBalanceUser(page,student);await page.goto(base+'/board/feedback');
    await expect(page.getByRole('button',{name:coach.nickname+' 선생님께 신청',exact:true})).toBeDisabled();
    await expect(page.getByRole('link',{name:/첫 한타 위치를 봐 주세요/})).toBeVisible();
  }finally{await f.cleanup();}
});
