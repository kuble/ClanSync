import { expect, test } from "@playwright/test";
import { createIsolatedBalanceFixture, loginIsolatedBalanceUser } from "./isolated-balance-fixture";

test("leader confirms a transfer from members, becomes a member and loses management access", async ({ page, browser }) => {
  test.setTimeout(120_000);
  page.setDefaultTimeout(15_000);
  const f = await createIsolatedBalanceFixture(3), peerContext = await browser.newContext();
  const base = f.path.replace(/\/balance$/, "");
  try {
    expect((await f.service.from("clan_members").update({ role: "officer" }).eq("clan_id", f.clanId).eq("user_id", f.users[2].id)).error).toBeNull();
    const peer = await peerContext.newPage();
    peer.setDefaultTimeout(15_000);
    await loginIsolatedBalanceUser(peer, f.users[2]);
    await peer.goto(base + "/manage?tab=members");
    await expect(peer.getByRole("button", { name: /클랜장 위임 후 멤버로 강등$/ })).toHaveCount(0);
    await loginIsolatedBalanceUser(page, f.users[0]);
    await page.goto(base + "/manage?tab=members");
    await expect(page.getByRole("button", { name: /클랜장 위임 후 멤버로 강등$/ })).toHaveCount(1);
    const button = page.getByRole("button", { name: `${f.users[0].nickname} 클랜장 위임 후 멤버로 강등`, exact: true });
    await button.click();
    const dialog = page.getByRole("dialog", { name: "클랜장 위임 및 강등", exact: true });
    await expect(dialog.getByRole("button", { name: "위임하고 멤버로 변경", exact: true })).toBeDisabled();
    await expect(dialog.getByRole("combobox", { name: "새 클랜장", exact: true }).getByRole("option")).toHaveCount(3);
    await dialog.getByRole("combobox", { name: "새 클랜장", exact: true }).selectOption(f.users[1].id);
    await expect(dialog).toContainText("본인은 멤버로 변경");
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    await page.screenshot({ path: test.info().outputPath("leadership-transfer-mobile.png"), animations: "disabled" });
    await dialog.getByRole("button", { name: "취소", exact: true }).click();
    let rows = await f.service.from("clan_members").select("user_id,role").eq("clan_id", f.clanId);
    expect(rows.data?.find(r => r.user_id === f.users[0].id)?.role).toBe("leader");
    await button.click();
    await expect(dialog.getByRole("combobox", { name: "새 클랜장", exact: true })).toHaveValue("");
    await dialog.getByRole("combobox", { name: "새 클랜장", exact: true }).selectOption(f.users[1].id);
    await dialog.getByRole("button", { name: "위임하고 멤버로 변경", exact: true }).click();
    await expect(page).toHaveURL(base);
    rows = await f.service.from("clan_members").select("user_id,role,status").eq("clan_id", f.clanId);
    expect(rows.data?.find(r => r.user_id === f.users[0].id)?.role).toBe("member");
    expect(rows.data?.find(r => r.user_id === f.users[1].id)?.role).toBe("leader");
    expect(rows.data?.filter(r => r.role === "leader")).toHaveLength(1);
    await page.goto(base + "/manage?tab=members");
    await expect(page.getByRole("heading", { name: "접근 권한이 없습니다", exact: true })).toBeVisible();
    await expect(page.getByRole("button", { name: /클랜장 위임 후 멤버로 강등$/ })).toHaveCount(0);
    await peerContext.clearCookies();
    await loginIsolatedBalanceUser(peer, f.users[1]);
    await peer.goto(base + "/manage?tab=members");
    await expect(peer.getByRole("button", { name: `${f.users[1].nickname} 클랜장 위임 후 멤버로 강등`, exact: true })).toBeVisible();
    await expect(peer.getByRole("button", { name: `${f.users[0].nickname} 운영진 승격`, exact: true })).toBeVisible();
    expect((await f.service.from("clans").select("ownership_transferred_at").eq("id", f.clanId).single()).data?.ownership_transferred_at).toBeTruthy();
    await page.goto("/profile");
    await page.waitForLoadState("networkidle");
    const accountTab = page.getByRole("tab", { name: "계정 정보", exact: true });
    await expect(async () => { await accountTab.click(); await expect(accountTab).toHaveAttribute("aria-selected", "true", { timeout: 1000 }); }).toPass({ timeout: 15_000 });
    await page.getByRole("button", { name: "오버워치 게임 정보", exact: true }).click();
    await page.getByRole("button", { name: /클랜 탈퇴/ }).first().click();
    const leave = page.getByRole("dialog");
    await leave.getByRole("button", { name: "클랜 탈퇴", exact: true }).click();
    await expect.poll(async () => (await f.service.from("clan_members").select("status").eq("clan_id", f.clanId).eq("user_id", f.users[0].id).single()).data?.status).toBe("left");
  } finally { try { await peerContext.close(); } finally { await f.cleanup(); } }
});
