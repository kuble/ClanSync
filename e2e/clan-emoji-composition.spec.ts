test("emoji crop is square, bounded, orientation aware and GIF processing remains gated", async () => {
  const left=await sharp({create:{width:40,height:80,channels:4,background:"#ff0000"}}).png().toBuffer();
  const input=await sharp({create:{width:160,height:80,channels:4,background:"#0000ff"}}).composite([{input:left,left:0,top:0}]).png().toBuffer();
  const output=await processEmojiImage(input,{x:80,y:0,size:80});
  expect(await sharp(output).metadata()).toMatchObject({width:128,height:128,format:"webp"});
  const pixel=await sharp(output).extract({left:64,top:64,width:1,height:1}).raw().toBuffer();
  expect(pixel[2]).toBeGreaterThan(240);expect(pixel[0]).toBeLessThan(10);
  for(const crop of [{x:-1,y:0,size:50},{x:0,y:0,size:1000},{x:0.5,y:0,size:20},{x:0,y:0,size:0}])await expect(processEmojiImage(input,crop)).rejects.toThrow();
  const frame=Buffer.from([255,0,0,255,0,0,255,255,0,255,0,255,255,255,0,255]);
  const gif=await sharp(Buffer.concat([frame,Buffer.from(frame.map((value,index)=>index%4===3?value:255-value))]),{raw:{width:2,height:4,channels:4,pageHeight:2}}).gif({delay:[80,120],loop:0}).toBuffer();
  await expect(processEmojiImage(gif)).rejects.toThrow("정적");
  expect(await sharp(await processEmojiImage(gif,null,true),{animated:true}).metadata()).toMatchObject({width:128,pageHeight:128,pages:2,format:"webp"});
  const id=randomUUID();expect(splitEmojiText("앞"+emojiToken(id)+"뒤",[{id,name:"환호"}])).toEqual([{text:"앞"},{emoji:{id,name:"환호"}},{text:"뒤"}]);
  expect(splitEmojiText(emojiToken(randomUUID()),[])[0].missing).toBe(true);
});

