import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { createIsolatedBalanceFixture, loginIsolatedBalanceUser } from "./isolated-balance-fixture";

test("게임 이름으로 클랜을 선택하고 모바일·스와이프·키보드로 탐색한다", async ({ page }) => {
  test.setTimeout(90_000);
  await page.emulateMedia({ reducedMotion: "reduce" });
  const f = await createIsolatedBalanceFixture(1);
  const otherClanId = randomUUID();
  let otherCreated = false;
  const battleTag = `Battle${f.users[0].id.slice(0, 8)}#1234`;
  const riotId = `Riot${f.users[0].id.slice(0, 8)}#QA1`;
  try {
    const game = await f.service.from("games").select("id").eq("slug", "valorant").single();
    expect(game.error).toBeNull();
    expect((await f.service.from("clans").insert({ id: otherClanId, name: `Identity-${f.users[0].id.slice(0, 8)}`, game_id: game.data!.id })).error).toBeNull();
    otherCreated = true;
    expect((await f.service.from("clan_members").insert({ clan_id: otherClanId, user_id: f.users[0].id, role: "member", status: "active" })).error).toBeNull();
    expect((await f.service.from("user_game_profiles").update({ battle_tag: battleTag }).eq("user_id", f.users[0].id).eq("game_id", f.gameId)).error).toBeNull();
    expect((await f.service.from("user_game_profiles").insert({ user_id: f.users[0].id, game_id: game.data!.id, game_uid: `provider:${randomUUID()}`, riot_id: riotId, is_verified: true })).error).toBeNull();
    await loginIsolatedBalanceUser(page, f.users[0]);
    await page.goto("/profile");
    const identity = page.getByRole("region", { name: "플레이어 소개", exact: true });
    const cards = identity.locator("article");
    const ow = cards.filter({ hasText: battleTag });
    const val = cards.filter({ hasText: riotId });
    const carousel = identity.getByRole("region", { name: "클랜 프로필", exact: true });
    const track = carousel.getByLabel("좌우로 넘겨 클랜 보기", { exact: true });
    const dots = carousel.getByRole("navigation", { name: "게임별 클랜", exact: true }).getByRole("button");
    const previous = dots.nth(0);
    const next = dots.nth(1);
    await expect(dots).toHaveCount(2);
    await expect(dots.filter({ hasText: "오버워치" })).toHaveCount(1);
    await expect(dots.filter({ hasText: "발로란트" })).toHaveCount(1);
    await expect(cards).toHaveCount(2);
    await expect(identity.getByRole("article")).toHaveCount(1);
    await expect(ow.getByText("배틀태그", { exact: true })).toHaveCount(1);
    await expect(val.getByText("라이엇 ID", { exact: true })).toHaveCount(1);
    await expect(ow.getByText(riotId, { exact: true })).toHaveCount(0);
    await expect(val.getByText(battleTag, { exact: true })).toHaveCount(0);
    await expect(identity.getByText(f.users[0].nickname, { exact: true })).toHaveCount(0);
    await expect(identity.getByRole("combobox")).toHaveCount(0);
    await expect(identity.getByText("함께하는 클랜", { exact: true })).toHaveCount(0);
    await expect(identity.locator('p').filter({ has: page.getByRole("img", { name: "오버워치 로고", exact: true }) })).toHaveCount(0);
    for (const width of [1280, 1023, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 });
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
      for (const button of await dots.all()) { const bounds = await button.boundingBox(); expect(bounds!.height).toBeGreaterThanOrEqual(44); }
      await track.focus();
      await track.press("Home");
      await expect(carousel.getByRole("status", { name: "현재 클랜", exact: true })).toHaveText("1 / 2");
      await expect(previous).toHaveAttribute("aria-current", "page");
      await expect(cards.nth(0)).toBeInViewport({ ratio: .95 });
      await next.click();
      await expect(carousel.getByRole("status", { name: "현재 클랜", exact: true })).toHaveText("2 / 2");
      await expect(next).toHaveAttribute("aria-current", "page");
      await expect(cards.nth(1)).toBeInViewport({ ratio: .95 });
      await expect(identity.getByRole("article")).toHaveCount(1);
      await previous.click();
      await expect(carousel.getByRole("status", { name: "현재 클랜", exact: true })).toHaveText("1 / 2");
      await track.focus();
      await track.press("ArrowRight");
      await expect(carousel.getByRole("status", { name: "현재 클랜", exact: true })).toHaveText("2 / 2");
    }
    await page.setViewportSize({ width: 320, height: 1400 });
    await track.press("End");
    await expect(cards.nth(1)).toBeInViewport({ ratio: .95 });
    await page.screenshot({ path: test.info().outputPath("profile-clan-identities-mobile.png") });
    await page.setViewportSize({ width: 1280, height: 1000 });
    await track.press("End");
    await expect(cards.nth(1)).toBeInViewport({ ratio: .95 });
    await page.screenshot({ path: test.info().outputPath("profile-clan-identities.png") });
    await page.setViewportSize({ width: 390, height: 1000 });
    await track.focus();
    await track.press("Home");
    await expect(carousel.getByRole("status", { name: "현재 클랜", exact: true })).toHaveText("1 / 2");
    const bounds = (await track.boundingBox())!;
    const cdp = await page.context().newCDPSession(page);
    const point = (x: number) => [{ x, y: bounds.y + 40 }];
    await cdp.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: point(bounds.x + bounds.width - 20) });
    for (const distance of [.25, .5, .75]) await cdp.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: point(bounds.x + bounds.width * (1 - distance)) });
    await cdp.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
    await expect(carousel.getByRole("status", { name: "현재 클랜", exact: true })).toHaveText("2 / 2");
    await cdp.detach();
    await page.getByRole("tab", { name: "계정 정보", exact: true }).click();
    await expect(page.getByText("미리보기용 ID입니다.", { exact: false })).toHaveCount(0);
    await page.getByRole("tab", { name: "플레이어 소개", exact: true }).click();
    const namecard = page.getByRole("region", { name: "공통 네임카드", exact: true });
    await expect(namecard.getByText("Player#1234", { exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await page.goto("/games");
    await page.locator('summary[aria-label="프로필 메뉴"]:visible').click();
    await expect(page.locator('summary[aria-label="프로필 메뉴"]:visible').locator("..").getByText("내 계정", { exact: true })).toBeVisible();
    await expect(page.getByText(f.users[0].nickname, { exact: true })).toHaveCount(0);
  } finally {
    if (otherCreated) expect((await f.service.from("clans").delete().eq("id", otherClanId)).error).toBeNull();
    await f.cleanup();
  }
});
