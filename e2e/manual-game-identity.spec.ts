import { createClient } from "@supabase/supabase-js";
import { expect, test } from "@playwright/test";
import { createIsolatedBalanceFixture, loginIsolatedBalanceUser } from "./isolated-balance-fixture";
import { loadGameOnboarding } from "../src/lib/onboarding/load-game-onboarding";
import { loadTestEnv } from "../scripts/test-env.mjs";

test("manual IDs remain unverified, allow clan entry and show honest profile status", async ({ page }, info) => {
  test.setTimeout(180_000);
  const f = await createIsolatedBalanceFixture(3);
  const [leader, member, newcomer] = await Promise.all(f.users.map((_, index) => f.memberClient(index)));
  let createdClanId: string | null = null;
  const createdName = `Manual-${f.clanId.slice(0, 8)}`;
  const profile = (index: number) => f.service.from("user_game_profiles").select("battle_tag,game_uid,is_verified,verified_at").eq("user_id", f.users[index].id).eq("game_id", f.gameId).single();
  try {
    const original = (await profile(0)).data!;
    expect((await leader.rpc("save_my_game_identity", { p_game_slug: "overwatch", p_identity: original.battle_tag! })).error).toBeNull();
    expect((await profile(0)).data).toEqual(original);
    expect((await leader.rpc("save_my_game_identity", { p_game_slug: "overwatch", p_identity: "ManualLeader#1001" })).error).toBeNull();
    expect((await profile(0)).data).toEqual({ battle_tag: "ManualLeader#1001", game_uid: original.game_uid, is_verified: false, verified_at: null });
    expect((await member.rpc("save_my_game_identity", { p_game_slug: "overwatch", p_identity: "OtherMember#2002" })).error).toBeNull();
    expect((await profile(0)).data?.battle_tag).toBe("ManualLeader#1001");
    const forged = await leader.from("user_game_profiles").update({ is_verified: true }).eq("user_id", f.users[0].id).select();
    expect(forged.error || !forged.data?.length).toBeTruthy();
    expect((await profile(0)).data?.is_verified).toBe(false);
    for (const value of ["plain-name", "Name#1", "Name#1234#5678"]) expect((await member.rpc("save_my_game_identity", { p_game_slug: "overwatch", p_identity: value })).error).toBeTruthy();
    expect((await member.rpc("save_my_game_identity", { p_game_slug: "pubg", p_identity: "Nope#1234" })).error).toBeTruthy();
    const env = loadTestEnv();
    const anonymous = createClient(env.NEXT_PUBLIC_SUPABASE_URL!, env.NEXT_PUBLIC_SUPABASE_ANON_KEY!, { auth: { persistSession: false } });
    expect((await anonymous.rpc("save_my_game_identity", { p_game_slug: "overwatch", p_identity: "NoLogin#1234" })).error).toBeTruthy();
    expect(await loadGameOnboarding(leader, f.users[0].id, "overwatch")).toMatchObject({ identityRegistered: true, authVerified: false, clanId: f.clanId });

    expect((await f.service.from("clan_members").delete().eq("clan_id", f.clanId).eq("user_id", f.users[2].id)).error).toBeNull();
    expect((await f.service.from("user_game_profiles").delete().eq("user_id", f.users[2].id).eq("game_id", f.gameId)).error).toBeNull();
    await loginIsolatedBalanceUser(page, f.users[2]);
    await page.goto("/profile");
    await expect(page.getByRole("region", { name: "플레이어 소개", exact: true })).toContainText("게임 ID 미등록");
    await page.goto("/games/overwatch/clan");
    await expect(page).toHaveURL(/\/games\/overwatch\/auth/);
    await page.getByRole("link", { name: "게임 선택으로", exact: true }).click();
    await expect(page).toHaveURL(/\/games$/);
    await page.getByRole("link", { name: /^오버워치 / }).click();
    await expect(page).toHaveURL(/\/games\/overwatch\/auth/);
    await expect(page.getByRole("list", { name: "클랜 참여 단계" })).toHaveCount(0);
    await expect(page.getByRole("textbox", { name: "테스트 배틀태그", exact: true })).toHaveCount(0);
    await expect(page.getByRole("button", { name: "계정 연동 준비 중", exact: true })).toHaveCount(0);
    for (const theme of ["dark", "light"]) {
      if (!(await page.locator("html").getAttribute("class"))?.split(" ").includes(theme)) await page.getByRole("button", { name: "라이트 테마", exact: true }).click();
      await expect(page.locator("html")).toHaveClass(new RegExp(`\\b${theme}\\b`));
      for (const width of [1304, 390, 320]) {
        await page.setViewportSize({ width, height: 884 });
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
        await expect(page.getByRole("button", { name: "게임 ID 저장", exact: true })).toBeInViewport();
        await page.screenshot({ path: info.outputPath(`game-id-${theme}-${width}.png`) });
      }
    }
    await page.setViewportSize({ width: 1304, height: 884 });
    await page.goto("/games/overwatch/auth?reauth=1&next=%2Fprofile");
    await expect(page.getByRole("link", { name: "프로필로 돌아가기", exact: true })).toHaveAttribute("href", "/profile");
    await page.goto("/games/valorant/auth");
    const riotInput = page.getByRole("textbox", { name: "라이엇 ID 직접 입력", exact: true });
    await expect(riotInput).toBeVisible();
    await expect(page.getByRole("textbox", { name: "테스트 라이엇 ID", exact: true })).toHaveCount(0);
    await riotInput.fill("BadId");
    await page.getByRole("button", { name: "게임 ID 저장", exact: true }).click();
    await expect(page.getByRole("alert").filter({ hasText: "라이엇 ID 전체" })).toBeVisible();
    await expect(riotInput).toHaveValue("BadId");
    await page.goto("/games/overwatch/auth");
    const input = page.getByRole("textbox", { name: "배틀태그 직접 입력", exact: true });
    await input.fill("BadTag");
    await page.getByRole("button", { name: "게임 ID 저장", exact: true }).click();
    await expect(page.getByRole("alert").filter({ hasText: "배틀태그 전체" })).toBeVisible();
    await expect(input).toHaveValue("BadTag");
    await input.fill("ManualNewcomer#3003");
    await page.getByRole("button", { name: "게임 ID 저장", exact: true }).click();
    await expect(page).toHaveURL(/\/games\/overwatch\/clan/);
    await expect(page.getByRole("list", { name: "클랜 참여 단계" })).toHaveCount(0);
    expect((await profile(2)).data).toMatchObject({ battle_tag: "ManualNewcomer#3003", is_verified: false, verified_at: null });
    const clan = await f.service.from("clans").select("name").eq("id", f.clanId).single();
    await page.goto(`/games/overwatch/clan?q=${encodeURIComponent(clan.data!.name)}`);
    await page.getByTestId(`clan-join-open-${f.clanId}`).click();
    await page.getByTestId(`clan-join-send-${f.clanId}`).click();
    await expect(page.getByText("가입 신청을 보냈습니다.", { exact: true })).toBeVisible();
    const request = await newcomer.from("clan_join_requests").select("id").eq("clan_id", f.clanId).eq("user_id", f.users[2].id).single();
    expect(request.error).toBeNull();
    expect((await leader.rpc("resolve_clan_join_request", { p_clan_id: f.clanId, p_request_id: request.data!.id, p_decision: "approved" })).error).toBeNull();
    await page.goto(f.path);
    await expect(page.getByRole("heading", { name: "내전 로비", exact: true })).toBeVisible();
    await page.goto("/profile");
    const status = page.getByLabel("오버워치 계정 인증 상태", { exact: true });
    await expect(status).toContainText("미인증");
    await expect(page.getByRole("region", { name: "플레이어 소개", exact: true })).toContainText("ManualNewcomer#3003");
    await status.screenshot({ path: info.outputPath("manual-verification-status.png") });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
    await page.getByRole("region", { name: "플레이어 소개", exact: true }).screenshot({ path: info.outputPath("manual-profile-mobile.png") });
    const response = await page.request.get(`/api/player-profiles/${f.users[0].id}?clanId=${f.clanId}`);
    expect(response.ok()).toBe(true);
    const body = await response.json();
    expect(body.profile.memberships.find((row: { clanId: string }) => row.clanId === f.clanId)).toMatchObject({ accountId: "ManualLeader#1001", isVerified: false });
    expect((await f.service.from("clan_members").delete().eq("clan_id", f.clanId).eq("user_id", f.users[1].id)).error).toBeNull();
    await page.context().clearCookies();
    await loginIsolatedBalanceUser(page, f.users[1]);
    await page.goto("/games/overwatch/clan");
    await page.getByRole("tab", { name: "클랜 생성", exact: true }).click();
    await page.getByRole("textbox", { name: "클랜명 *", exact: true }).fill(createdName);
    await page.getByRole("button", { name: "클랜 만들기", exact: true }).click();
    await expect(page).toHaveURL(/\/clan\/[\da-f-]+\/welcome/);
    createdClanId = new URL(page.url()).pathname.split("/").at(-2)!;
    expect((await profile(1)).data?.is_verified).toBe(false);
  } finally {
    createdClanId ??= (await f.service.from("clans").select("id").eq("name", createdName).eq("game_id", f.gameId).maybeSingle()).data?.id ?? null;
    if (createdClanId) await f.service.from("clans").delete().eq("id", createdClanId);
    await Promise.all([leader.auth.signOut(), member.auth.signOut(), newcomer.auth.signOut()]);
    await f.cleanup();
  }
});
